import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

import { describe, expect, it } from "vitest";

import { parseTrialBalance } from "../../ingest/parse-workbook";
import { normalizeTrialBalance } from "../../ingest/normalize";
import { deriveCreditNatureGroupings, type TemplateLine } from "../catalog";
import { computePnl } from "../pnl";
import type { LedgerMapEntry, ManualInputs } from "../types";
import seedMap from "../seed/ledger-map.tirupati.json";
import expectedMaster from "./fixtures/master_tb.expected.json";
import expectedPnl from "./fixtures/pnl.expected.json";
import tirupatiTemplate from "./fixtures/tirupati.template.json";

const fx = (name: string) => readFileSync(fileURLToPath(new URL(`./fixtures/${name}`, import.meta.url)));

// Generated by scripts/gen-tirupati-template.mts from catalog.ts's own
// DEFAULT_TEMPLATE_LINES, Tirupati's real template, as a DB-free fixture so
// these tests stay pure/fast (see the same reasoning on seedMap above).
const TEMPLATE = tirupatiTemplate.template as TemplateLine[];
const CREDIT_NATURE_GROUPINGS = deriveCreditNatureGroupings(TEMPLATE);

// The manual (non-Trial-Balance) figures the preparer used for April'26.
const APR26_MANUAL: ManualInputs = {
  accessoriesSales: 1977513.81,
  otherSales: 6214935.7,
  discountReceived: 1092,
  employeeBenefitExpense: 756842,
  closingStock: 53427016.35,
  cashSalary: 437361,
  staffWelfare: 0,
  commission: 0,
  depreciation: 0,
  interestExpense: 648343,
};

const close = (actual: number, expected: number, tol = 1) => {
  expect(Math.abs(actual - expected), `expected ${actual} ≈ ${expected}`).toBeLessThanOrEqual(tol);
};

describe("Trial Balance → Master_TB normalization", () => {
  const parsed = parseTrialBalance(fx("Tirupati_Trial.xlsx"));
  const { rows, unmapped } = normalizeTrialBalance(parsed, seedMap as LedgerMapEntry[], CREDIT_NATURE_GROUPINGS);

  it("extracts the leaf ledgers (skipping group headers & Grand Total)", () => {
    expect(rows.length).toBe(75); // 76 Master rows minus the manual "Employee Benefit Expense"
    expect(parsed.grandTotal?.debit).toBeGreaterThan(0);
  });

  it("maps every raw ledger (no unmapped, given the Tirupati seed)", () => {
    expect(unmapped).toEqual([]);
  });

  const oracleByLedger = new Map(
    (expectedMaster as { particulars: string; opening: number; closing: number }[]).map((r) => [
      r.particulars,
      r,
    ]),
  );
  // The reference workbook manually forces Sundry Creditors' closing to a credit
  // sign that does NOT satisfy closing = opening + debit − credit. Our recovered
  // sign is the accounting-correct one; this deviation is surfaced to the user.
  const KNOWN_SOURCE_OVERRIDES = new Set(["Sundry Creditors"]);

  it("recovers signed opening & closing matching the reference Master_TB", () => {
    const mismatches: string[] = [];
    for (const row of rows) {
      const exp = oracleByLedger.get(row.particulars);
      if (!exp || KNOWN_SOURCE_OVERRIDES.has(row.particulars)) continue;
      if (Math.abs(row.opening - exp.opening) > 1 || Math.abs(row.closing - exp.closing) > 1) {
        mismatches.push(
          `${row.particulars} [${row.grouping}] close ${row.closing} vs ${exp.closing} | open ${row.opening} vs ${exp.opening}`,
        );
      }
    }
    if (mismatches.length) console.log("SIGN MISMATCHES:\n" + mismatches.join("\n"));
    expect(mismatches).toEqual([]);
  });

  it("flags Sundry Creditors as a source sign override (breaks the balance identity)", () => {
    const mine = rows.find((r) => r.particulars === "Sundry Creditors")!;
    const exp = oracleByLedger.get("Sundry Creditors")!;
    close(mine.closing, mine.opening + mine.debit - mine.credit); // ours is identity-consistent
    expect(Math.sign(mine.closing)).not.toBe(Math.sign(exp.closing)); // workbook forced the opposite sign
  });

  it("satisfies closing = opening + debit − credit on every row", () => {
    for (const row of rows) close(row.closing, row.opening + row.debit - row.credit);
  });
});

describe("P&L engine vs finished MIS (April'26)", () => {
  const parsed = parseTrialBalance(fx("Tirupati_Trial.xlsx"));
  const { rows } = normalizeTrialBalance(parsed, seedMap as LedgerMapEntry[], CREDIT_NATURE_GROUPINGS);
  const pnl = computePnl(rows, APR26_MANUAL, TEMPLATE);
  const oracle = expectedPnl as Record<string, number>;

  it("matches headline figures", () => {
    close(pnl.totals.revenue, oracle["Revenue From Operations"]);
    close(pnl.totals.cogs, oracle["COGS"]);
    close(pnl.totals.grossProfit, oracle["Gross Profit"]);
    close(pnl.totals.indirectExpense, oracle["Total Indirect Expense"]);
    close(pnl.totals.ebitda, oracle["EBITDA"]);
    close(pnl.totals.ebit, oracle["EBIT"]);
    close(pnl.totals.ebt, oracle["EBT"]);
  });

  it("matches every named line item present in the workbook", () => {
    for (const line of pnl.lines) {
      if (line.emphasis === "section") continue;
      const exp = oracle[line.label];
      if (exp === undefined) continue; // label not individually listed in the sheet
      close(line.value, exp);
    }
  });
});
