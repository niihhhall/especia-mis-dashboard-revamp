// Generate supabase/seed.sql from the Tirupati seed ledger map, so a fresh
// `supabase db reset` loads the demo company + its ledger→grouping mapping.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const seed = JSON.parse(
  readFileSync(fileURLToPath(new URL("../src/lib/mis/seed/ledger-map.tirupati.json", import.meta.url))),
);

const COMPANY_ID = "11111111-1111-1111-1111-111111111111";
const esc = (s) => (s == null ? "null" : `'${String(s).replace(/'/g, "''")}'`);

let sql = `-- Auto-generated by scripts/gen-seed.mjs — do not edit by hand.
insert into public.companies (id, slug, name, fy_start_month, pan, gst, cin, address)
values (
  '${COMPANY_ID}', 'tirupati', 'Tirupati Automart Private Limited', 4,
  null, null, 'U50300WB2019PTC234722',
  'Plot 534, Bhakuri, Berhampore, Murshidabad, West Bengal 742101'
)
on conflict (id) do nothing;

insert into public.ledger_map (company_id, ledger_name, grouping, bs_pl, classification, source) values
`;

const rows = seed.map(
  (e) =>
    `  ('${COMPANY_ID}', ${esc(e.ledger)}, ${esc(e.grouping)}, ${esc(e.bs_pl)}, ${esc(e.classification)}, 'manual')`,
);
sql += rows.join(",\n") + "\non conflict (company_id, ledger_name) do nothing;\n";

writeFileSync(fileURLToPath(new URL("../supabase/seed.sql", import.meta.url)), sql);
console.log(`Wrote supabase/seed.sql with 1 company + ${seed.length} ledger_map rows`);
